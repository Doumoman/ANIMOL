            { "undersides/wood/span_04.png", new SpriteSpec(256f, 0.5f, 0.6875f) },
        };

        private static bool TryGetSpec(string relative, out SpriteSpec spec)
        {
            return Specs.TryGetValue(relative, out spec);
        }

        private void OnPreprocessTexture()
        {
            string normalized = assetPath.Replace('\\', '/');
            int index = normalized.IndexOf(Marker, StringComparison.Ordinal);
            if (index < 0 || !normalized.EndsWith(".png", StringComparison.OrdinalIgnoreCase)) return;
            string relative = normalized.Substring(index + Marker.Length);
            SpriteSpec spec;
            if (!TryGetSpec(relative, out spec)) return;
            var importer = (TextureImporter)assetImporter;
            importer.textureType = TextureImporterType.Sprite;
            importer.spriteImportMode = SpriteImportMode.Single;
            importer.spritePixelsPerUnit = spec.Ppu;
            importer.filterMode = FilterMode.Bilinear;
            importer.textureCompression = TextureImporterCompression.Uncompressed;
            importer.crunchedCompression = false;
            importer.mipmapEnabled = false;
            importer.wrapMode = TextureWrapMode.Clamp;
            importer.alphaIsTransparency = true;
            importer.npotScale = TextureImporterNPOTScale.None;
            importer.maxTextureSize = 4096;
            importer.ClearPlatformTextureSettings("Android");
            importer.ClearPlatformTextureSettings("iPhone");
            importer.ClearPlatformTextureSettings("Standalone");
            importer.ClearPlatformTextureSettings("WebGL");
            var settings = new TextureImporterSettings();
            importer.ReadTextureSettings(settings);
            settings.spriteAlignment = (int)SpriteAlignment.Custom;
            settings.spritePivot = spec.Pivot;
            settings.spriteMeshType = SpriteMeshType.FullRect;
            settings.spriteGenerateFallbackPhysicsShape = false;
            importer.SetTextureSettings(settings);
        }
    }
