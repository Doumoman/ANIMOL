args=ap.parse_args();B=args.baseline.resolve();R=args.package.resolve();errors=[]
def need(ok,message):
 if not ok:errors.append(message)
def read(p):return json.loads(p.read_text())
def sha(p):return hashlib.sha256(p.read_bytes()).hexdigest()
def image_data(p):
 with Image.open(p) as im:
  im.load();r=im.convert('RGBA');return hashlib.sha256(r.tobytes()).hexdigest(),r.getchannel('A').getbbox() is None,list(im.size)
def refs(v,out):
 if isinstance(v,str) and v.startswith('sources/') and v.endswith('.png'):out.add(v)
 elif isinstance(v,dict):
  for x in v.values():refs(x,out)
 elif isinstance(v,list):
  for x in v:refs(x,out)
baselineMain=read(B/'manifest.json');new=read(R/args.manifest)
need(baselineMain.get('packageId')=='ANIMOL_SUNSET_SANCTUM_CARTOON_V01','Wrong V01 baseline identity')
