aliasMap={}
for key in ['endpointAliases','compatibilityAliases','aliases']:
 v=new.get(key,{})
 if isinstance(v,dict):aliasMap.update({f:t if isinstance(t,str) else t.get('latestFrame',t.get('aliasOf')) for f,t in v.items()})
