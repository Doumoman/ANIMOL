if not args.group:need(len(newAssets)==1024,'V02 must retain 1024 runtime slots')
allowed=set(read(args.allow_transparent_unchanged)) if args.allow_transparent_unchanged else set()
need(all(isinstance(f,str) for f in allowed),'Invalid transparent exception list')
