newRefs=set();refs(new,newRefs);newSourceEvidence={}
for f in sorted(newRefs):
 p=R/f;need(p.is_file(),'Missing V02 native source:'+f)
 if not p.is_file():continue
 try:
  rgba,empty,size=image_data(p);h=sha(p)
  need(h not in oldSourceHashes,'V01 native source reused:'+f)
  need(rgba not in oldSourceDecoded,'V01 native decoded RGB(A) reused with reencoding:'+f)
  newSourceEvidence[f]={'sha256':h,'decodedRgbaSha256':rgba,'size':size,'differsFromV01Native':h not in oldSourceHashes}
 except Exception as e:errors.append('V02 native PNG decode failed:'+f+':'+type(e).__name__)
declared=new.get('nativeSources',new.get('sources',[]))
if isinstance(declared,list):
 for a in declared:
  if not isinstance(a,dict):continue
  f=a.get('file',a.get('source'))
  if isinstance(f,str) and f.startswith('sources/') and 'sha256' in a:need(f in newSourceEvidence and newSourceEvidence[f]['sha256']==a['sha256'],'Native declaration SHA mismatch:'+f)
immutable=['width','height','ppu','pivot','logicalRect','footprintCells','groundFootprintRect','family','heading','state','deriveColliderFromAlpha','actualGameplayFootprintCells','existingGameplayId','artSlotCells','registerGameplayCellFromThisRecord','occupancyParticipation','visualOnly','launchVector','landingOffsetCells','permanentTravelHeading','pairChannel','pairGlyph','actualPullHeading','pullHeading','mouthHeading','feedbackHeading','vector','directionVector','stopAxis','travelAxis','pullTravelHeading','worldTravelVector','headingVector','bodyAxis','stopbarAxis','noTransportArrow','opticalAnchorPixel','gateOccupiedCellCount','clearPassagePixels','outputCellIsCheckOnly','crackIsHealthState','addsHitRequirement','linkedGlyph']
